// ステージ5 白川郷・合掌の里（昼→夕方／雪・吹雪・霧）。主役：滑る氷と、合掌造りの急な屋根（滑り台）
// 導入：集落の入口。平らな氷で滑りを教える。雪の丘から合掌造りの屋根を滑り下りる（下は地面）。
//       つららの下がる軒下の行き止まりにさるぼぼ0（つららを一本ずつ落としてから取る）
// 展開：屋根を滑って勢いで穴を越える。氷の上の穴。吹雪の横風（はじめは穴のない所で）。雪に埋もれた隠し通路
// 山場：雪原から屋根を3つ滑り下りる（横風・雪雲）→ 飛騨牛串の先に氷の上の群れ → つららの軒下と穴
// ボス：雪の広場で雪鬼
import { Stage } from './lib.mjs';

export function build() {
  const b = new Stage({ id: 5, name: '白川郷・合掌の里', theme: 'shirakawa', width: 300, height: 26, timeOfDay: 'day', timeFlow: ['day', 'dusk'], weathers: ['snow', 'blizzard', 'fog'], ground: 'N' });
  const D = (s, x, y, p) => b.decor('prop_' + s, x, y, p);
  // 屋根の滑り台（右下がり）：(x, top) から n 段。下は家の壁（W）で地面まで
  const roof = (x, top, n) => { for (let i = 0; i < n; i++) { b.set(x + i, top + i, '>'); for (let y = top + i + 1; y < b.H; y++) b.set(x + i, y, 'W'); } };
  const icicle = (x, y) => b.ent('icicle', x, y);
  b.f = 19;

  // ===================== 導入（0〜76）=====================
  b.flat(15);                                      // 0-14
  b.start(3, 18);
  b.sign('shirakawago', 8, 18, '白川郷', '白川郷は庄川の流れる山あいの村。合掌造りの家々が残る荻町の集落は、1995年に五箇山とともに世界遺産に登録された。');
  D('cedar', 1, 18); D('snowman', 12, 18); D('gassho', 6, 18, { z: -8 });
  b.flat(10, { top: 'I' });                        // 15-24 平らな氷（穴なし）
  b.enemy('walker', 'yukidama', 21, 18, { range: 3 });
  b.coins(16, 23, 16);
  b.up45(3);                                       // 25-27 → f16
  b.flat(2);                                       // 28-29
  b.up45(3);                                       // 30-32 → f13
  b.flat(2);                                       // 33-34 雪の丘のてっぺん
  roof(35, 13, 6);                                 // 35-40 屋根の滑り台（下は地面）
  b.x = 41; b.to(19).flat(7);                      // 41-47
  b.coin(36, 12).coin(38, 14).coin(40, 16).coin(42, 17).coin(44, 17);
  D('gassho', 38, 18, { z: -1 });
  // 軒下：上は通り道、下は行き止まりのトンネル（つららの奥にさるぼぼ0）
  b.rect(44, 16, 46, 18, 'N');                     // 段
  b.flat(16);                                      // 48-63
  b.rect(48, 13, 61, 16, 'N');                     // 軒（上を歩ける）
  b.rect(62, 13, 63, 18, 'N');                     // トンネルの奥の壁
  icicle(51, 17); icicle(54, 17); icicle(57, 17);
  b.sarubobo(0, 60, 18, '見えているが取り方を考える（つららを落としてから）');
  b.coins(49, 59, 18);
  b.coins(50, 60, 11);
  b.enemy('flyer', 'yukigumo', 70, 12, { amp: 1, range: 3 });
  b.flat(13);                                      // 64-76
  b.enemy('hopper', 'yukiusagi', 72, 18);
  D('gassho', 70, 18, { z: -8 }); D('snowman', 66, 18);

  // ===================== 展開（77〜152）=====================
  b.checkpoint(0, 78, 18);
  b.flat(5);                                       // 77-81
  b.sign('gassho', 80, 18, '合掌造り', '合掌造りは手のひらを合わせたような急な茅葺き屋根の家。雪が落ちやすい形で、広い屋根裏は昔、養蚕の作業場として使われた。');
  b.up45(3); b.flat(2); b.up45(3); b.flat(3);      // 82-92 → f13
  roof(93, 13, 5);                                 // 93-97 滑り台 → 穴を越える
  b.coin(94, 11).coin(96, 13).coin(98, 14).coin(100, 14).coin(102, 15);
  b.x = 98; b.to(19).gap(4);                       // 98-101 穴
  b.flat(4);                                       // 102-105
  b.enemy('spiky', 'koritoge', 104, 18, { range: 1 });
  b.flat(6, { top: 'I' });                         // 106-111 氷
  b.gap(3);                                        // 112-114 穴
  b.arc(110, 18, 115, 18, 2);
  b.flat(6, { top: 'I' });                         // 115-120 氷
  b.gap(3);                                        // 121-123 穴
  b.arc(119, 18, 124, 18, 2);
  b.flat(6);                                       // 124-129
  // 吹雪の横風（向かい風）。はじめは穴のない所で
  b.ent('windZone', 0, 0, { x0: 130, x1: 152, force: -150, period: 4 });
  b.flat(10);                                      // 130-139
  b.enemy('hopper', 'yukiusagi', 136, 18);
  // 雪に埋もれた隠し通路：地面の雪（H）を踏み抜いて下の部屋へ
  b.flat(13);                                      // 140-152
  b.room(140, 19, 151, 25, 'N');
  b.row(143, 144, 19, 'H');                        // 入口（見た目は雪の地面）
  b.rect(143, 22, 144, 24, 'N');                   // 入口の下の台
  b.coinCol(143, 15, 17);
  b.coins(145, 150, 24).coins(146, 149, 22).coins(141, 142, 24);
  b.sarubobo(1, 150, 24, '隠し部屋の奥');
  b.ent('heart', 141, 22);
  D('snowman', 148, 18); D('cedar', 138, 18);

  // ===================== 山場（153〜245）=====================
  b.sign('yui', 154, 18, '結', '合掌造りの屋根の茅のふき替えは、村の人々が力を合わせる「結」という助け合いで行われてきた。大勢で一気に屋根をふき替える。');
  b.flat(3);                                       // 153-155
  b.up45(3); b.flat(2); b.up45(3); b.flat(2); b.up45(3);   // 156-168 → f10
  b.flat(4);                                       // 169-172 雪原（P1）
  roof(173, 10, 4);                                // 173-176 屋根1
  b.x = 177; b.to(14).gap(3);                      // 177-179 穴
  b.flat(6);                                       // 180-185 P2
  b.coin(174, 9).coin(176, 11).coin(178, 11).coin(180, 12);
  b.enemy('flyer', 'yukigumo', 183, 8, { amp: 1, range: 2 });
  // さるぼぼ2：P2 の上の高い足場。ハクの二段ジャンプ・ミナモの大ジャンプなら P2 から、
  // リーフは右の煙出しの壁をけって。ゲンは雪原の端から崩れる足場を経由して
  b.ent('fallingPlatform', 176, 10, { w: 2, kind: 'wood' });
  b.row(179, 181, 9, '-');
  b.sarubobo(2, 180, 8, '能力があると楽に取れる');
  b.rect(182, 6, 182, 9, 'W');
  roof(186, 14, 4);                                // 186-189 屋根2
  b.x = 190; b.to(18).gap(3);                      // 190-192 穴
  b.coin(187, 13).coin(189, 15).coin(191, 15).coin(193, 16);
  b.ent('windZone', 0, 0, { x0: 186, x1: 206, force: -170, period: 3.5 });
  b.flat(13);                                      // 193-205
  D('gassho', 199, 17, { z: -8 });
  b.ent('skewer', 204, 17);
  // 飛騨牛串の先：氷の上の群れ
  b.flat(22, { top: 'I' });                        // 206-227
  b.enemy('walker', 'yukidama', 209, 17, { range: 2 });
  b.enemy('hopper', 'yukiusagi', 212, 17);
  b.enemy('spiky', 'koritoge', 215, 17, { range: 2 });
  b.enemy('walker', 'yukidama', 218, 17, { range: 2 });
  b.enemy('hopper', 'yukiusagi', 221, 17);
  b.enemy('flyer', 'yukigumo', 216, 11, { amp: 1, range: 4 });
  b.coins(208, 225, 14);
  // つららの軒下と穴
  b.rect(228, 11, 243, 12, 'N');
  b.flat(4);                                       // 228-231
  b.gap(3);                                        // 232-234
  b.flat(3);                                       // 235-237
  b.gap(3);                                        // 238-240
  b.flat(5);                                       // 241-245
  for (const x of [229, 233, 236, 239, 242]) icicle(x, 13);
  b.arc(231, 17, 235, 17, 1).arc(237, 17, 241, 17, 1);

  // ===================== ボス（246〜300）=====================
  b.flat(24);                                      // 246-269
  b.checkpoint(1, 249, 17);
  b.sign('gosetsu', 254, 17, '豪雪の里', '白川郷は冬に雪が深く積もる豪雪地帯。急な屋根は雪の重みに耐え、雪を落としやすくするための工夫だといわれる。');
  D('snowman', 258, 17); D('gassho', 263, 17, { z: -8 });
  b.coins(257, 266, 15);
  b.arena('yukioni', 18, { wall: 'N', floor: 'N', fill: 'N' });
  D('cedar', 276, 17, { z: -6 }); D('cedar', 294, 17, { z: -6 });

  b.area('導入', 0, 77).area('展開', 77, 153).area('山場', 153, 246).area('ボス', 246, 300);
  return b;
}
