// ステージ1 金華山・岐阜城（昼）。主役：登山道の坂とロープウェイ（gondola）
// 導入：岐阜公園から坂を登る。空堀の上で初めてゴンドラ（落ちても階段で戻れる）
// 展開：登山道の坂と穴。谷をゴンドラで渡る（ここは落ちるとミス）。崖の中に隠し部屋
// 山場：石垣を登る縦エリア → 天守の中（室内）→ 飛騨牛串の先にサルとイノシシの群れ
// ボス：山頂の森で大ムササビ
import { Stage } from './lib.mjs';

export function build() {
  const b = new Stage({ id: 1, name: '金華山・岐阜城', theme: 'kinka', width: 300, height: 44, timeOfDay: 'day', weathers: ['sunny', 'cloudy', 'shower'] });
  b.f = 40;
  const D = (s, x, y, p) => b.decor('prop_' + s, x, y, p);

  // ===================== 導入（0〜70）=====================
  b.flat(16);
  b.start(3, 39);
  b.sign('kinka', 7, 39, '金華山', '金華山は岐阜市の長良川のほとりにそびえる標高329メートルの山。山頂に岐阜城の天守が建ち、ふもとの岐阜公園から登山道がのびている。');
  D('pine', 1, 39); D('toro', 5, 39); D('torii_small', 12, 39); D('bush', 14, 39, { z: 2 });
  b.arc(9, 39, 13, 39, 1);                         // 最初の小さなジャンプ
  b.up22(2);                                       // 16-19  → f38（ゆるい坂）
  b.coins(16, 19, 36);
  b.flat(8);                                       // 20-27
  b.enemy('walker', 'uribo', 25, 37, { range: 3 });
  D('cedar', 21, 37); D('grass', 27, 37);
  b.up45(2);                                       // 28-29 → f36（急な坂）
  b.coin(28, 35).coin(29, 34);
  b.flat(6);                                       // 30-35
  b.gap(2);                                        // 36-37 最初の穴（2マス）
  b.arc(34, 35, 39, 35, 2);
  b.flat(8);                                       // 38-45 ゴンドラ乗り場
  D('toro', 39, 35, { light: null });
  // 空堀の上を渡る、最初のゴンドラ（落ちても空堀の底を歩いて右の階段から上がれる）
  b.ent('gondola', 46, 36, { x2: 54, y2: 32, speed: 2.2 });   // x,y＝床の左端と上面の行
  b.to(39).flat(7);                                // 46-52 空堀の底（f39）
  b.to(37).flat(2);                                // 53-54 階段
  b.to(34).flat(2);                                // 55-56
  b.to(32).flat(3);                                // 57-59 ...ここから上の岸
  // 空堀の上の足場とさるぼぼ0（見えているが取り方を考える：ゴンドラから跳び移る／階段の途中から跳ぶ）
  b.row(48, 50, 32, '-');
  b.row(52, 53, 33, '-');
  b.sarubobo(0, 49, 30, '見えているが取り方を考える');
  b.coins(47, 51, 37);
  D('rock', 48, 38); D('grass', 51, 38);
  b.flat(13);                                      // 60-72（f32）
  b.enemy('flyer', 'karasu', 66, 27, { amp: 1, range: 4 });
  D('pine', 62, 31); D('toro', 70, 31);

  // ===================== 展開（73〜150）=====================
  b.checkpoint(0, 73, 31);
  b.flat(3);                                       // 73-75
  b.sign('ropeway', 76, 31, '金華山ロープウェー', 'ふもとの岐阜公園と山頂近くを結ぶロープウェーがあり、数分で山の上へ行ける。窓からは長良川と岐阜の町並みが見わたせる。');
  b.flat(3);                                       // 76-78
  b.up45(3);                                       // 79-81 → f29
  b.coin(79, 30).coin(80, 29).coin(81, 28);
  b.flat(8);                                       // 82-89
  b.enemy('spiky', 'iga', 86, 28, { range: 3 });
  b.coins(84, 88, 25);
  b.down22(2);                                     // 90-93 → f31
  b.flat(4);                                       // 94-97
  b.enemy('walker', 'uribo', 96, 30, { range: 2 });
  b.gap(4);                                        // 98-101 穴（4マス）
  b.arc(97, 30, 102, 30, 2);
  b.flat(6);                                       // 102-107
  D('cedar', 104, 30);
  b.up22(3);                                       // 108-113 → f28
  b.coins(108, 113, 25);
  b.flat(6);                                       // 114-119 ゴンドラ乗り場
  // カラスはゴンドラの客の頭より上（QA：以前は乗っている高さを飛び、当たると谷へ落とされて1面には厳しかった）。コインを取りに跳ぶと狙われる
  b.enemy('flyer', 'karasu', 130, 17, { amp: 1, range: 3 });
  D('toro', 115, 27);
  // 谷を渡るゴンドラ（落ちるとミス）
  b.ent('gondola', 120, 28, { x2: 133, y2: 22, speed: 2.4 });
  for (let i = 0; i <= 6; i++) b.coin(121 + i * 2, 24 - Math.round(i * 0.9));
  b.gap(16);                                       // 120-135 谷
  b.to(22).flat(26);                               // 136-161 上の崖（f22）
  D('pine', 141, 21); D('rock', 156, 21);
  // 崖の中の隠し部屋：地面のふりをした H を踏み抜いて落ちる。中の石の段で戻る
  b.room(142, 22, 155, 31);
  b.row(147, 148, 22, 'H');                        // 入口（見た目は地面）
  b.rect(147, 25, 148, 30, '#');                   // 入口の真下の柱（上面に立つと3段で地上へ）
  b.rect(150, 28, 151, 30, '#');                   // 床から柱へ上る段
  // 左の奥（さるぼぼ）からも柱へ戻れる段（QA：以前は柱の左に落ちると高さ6の柱を登れず、ゲン・ミナモは出られなかった）
  b.rect(146, 28, 146, 30, '#');
  b.coinCol(147, 18, 20);                          // 入口の目印（上から落ちてくるコイン）
  b.coins(143, 145, 30).coins(143, 145, 28).coins(152, 154, 30);
  b.sarubobo(1, 143, 30, '隠し部屋の奥');
  b.ent('heart', 153, 30);
  b.enemy('walker', 'uribo', 158, 21, { range: 2 });

  // ===================== 山場（162〜248）：石垣の縦エリア → 天守の中 =====================
  // 石垣：左の石垣と右の石垣の間をジグザグに登る（どの段も高さ3）
  b.rect(161, 2, 161, 19, 'S');                    // 左の石垣（下の2マスが入口。リーフは壁キックに使える）
  b.rect(162, 22, 196, 43, 'S');                   // 石垣の底
  b.row(169, 172, 19, '-');                        // A
  b.rect(162, 16, 166, 16, 'S');                   // B（左の石垣から張り出す）
  b.row(169, 173, 13, '-');                        // C
  b.rect(176, 10, 196, 21, 'S');                   // 右の石垣（上が天守への道）
  b.coins(170, 172, 17).coins(163, 165, 14).coins(170, 172, 11);
  b.arc(173, 12, 177, 9, 1);
  b.enemy('flyer', 'karasu', 166, 11, { amp: 1, range: 2 });
  b.enemy('thrower', 'saru', 181, 9, { face: -1 });
  // さるぼぼ2：左上の張り出し。ハクの二段ジャンプ・ミナモの大ジャンプ・リーフの壁キックならCから一気に。
  // ゲンは崩れる足場を2つ渡って行く
  b.row(162, 164, 9, '-');
  b.sarubobo(2, 163, 7, '能力があると楽に取れる');
  b.ent('fallingPlatform', 172, 10, { w: 2, kind: 'wood' });
  b.ent('fallingPlatform', 168, 10, { w: 2, kind: 'wood' });
  b.coins(165, 167, 6);
  D('castle_wall', 186, 9, { z: -6 }); D('pine', 178, 9);
  // 天守の中（室内）：天井のある木の床
  b.rect(197, 10, 247, 43, '#');
  b.rect(186, 1, 247, 3, 'W');                     // 天井
  b.rect(186, 0, 247, 0, 'R');                     // 屋根
  b.rect(186, 10, 247, 10, 'W');                   // 木の床
  b.rect(186, 4, 186, 6, 'W');                     // 入口の上の壁（下の3マスが入口）
  b.rect(247, 4, 247, 6, 'W');                     // 出口の上の壁
  b.sign('tenshu', 190, 9, '岐阜城の天守', '今の天守は1956年（昭和31年）に再建されたもの。中は資料館になっていて、最上階の展望台からは濃尾平野を一望できる。');
  D('chochin', 194, 6, { z: -2, light: { r: 90, color: '#ffbf6a' } });
  // 段と通り抜け足場
  b.rect(198, 8, 201, 9, 'W');
  b.enemy('walker', 'uribo', 204, 9, { range: 2 });
  b.row(205, 209, 7, '-');
  b.coins(205, 209, 5);
  b.rect(212, 7, 215, 9, 'W');
  b.ent('skewer', 218, 9);
  // 床の穴（幅3）
  b.clear(220, 10, 222, 43);
  b.arc(218, 9, 224, 9, 1);
  // 飛騨牛串の先：サルとイノシシの群れ
  b.enemy('charger', 'inoshishi', 228, 9, { face: -1 });
  b.enemy('thrower', 'saru', 231, 9, { face: -1 });
  b.enemy('walker', 'uribo', 234, 9, { range: 2 });
  b.enemy('charger', 'inoshishi', 238, 9, { face: -1 });
  b.enemy('walker', 'uribo', 242, 9, { range: 2 });
  b.coins(226, 244, 6);
  D('chochin', 230, 6, { z: -2, light: { r: 90, color: '#ffbf6a' } });
  D('chochin', 240, 6, { z: -2, light: { r: 90, color: '#ffbf6a' } });

  // ===================== ボス（248〜300）=====================
  // 天守を出て山頂の森へ
  b.rect(248, 10, 270, 43, '#');
  b.checkpoint(1, 252, 9);
  b.sign('dosan', 256, 9, '岐阜城と斎藤道三', '戦国時代、斎藤道三がこの山の城を本拠とした。のちに織田信長が城を攻め取り、町の名を「岐阜」と改めたと伝えられている。');
  D('pine', 260, 9); D('toro', 264, 9);
  b.coins(259, 266, 6);
  b.arena('musasabi', 10, { wall: 'S' });
  D('pine', 276, 9, { z: -6 }); D('cedar', 284, 9, { z: -6 }); D('pine', 293, 9, { z: -6 });

  b.area('導入', 0, 73).area('展開', 73, 161).area('山場', 161, 248, true).area('ボス', 248, 300);
  return b;
}
